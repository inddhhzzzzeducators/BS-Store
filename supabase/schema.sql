-- BS Store starter schema for Supabase (PostgreSQL)
-- Run this in Supabase Dashboard -> SQL Editor.
-- Row Level Security is enabled on every application table.
-- Never put a service_role key in the browser.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text,
  category text not null,
  unit text not null,
  retail_price numeric(10,2) not null check (retail_price >= 0),
  wholesale_price numeric(10,2) not null check (wholesale_price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete restrict,
  status text not null default 'pending'
    check (status in ('pending','confirmed','packed','out_for_delivery','delivered','cancelled')),
  shopping_mode text not null default 'retail' check (shopping_mode in ('retail','wholesale')),
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  delivery_address text,
  customer_note text,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

create index if not exists products_category_idx on public.products(category);
create index if not exists orders_customer_created_idx on public.orders(customer_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);

create or replace function public.is_bs_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

-- New sign-ups always receive the customer role. Admin must be assigned manually
-- by the project owner in the Supabase SQL Editor after verifying the account.
create or replace function public.handle_new_bs_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_bs on auth.users;
create trigger on_auth_user_created_bs
  after insert on auth.users
  for each row execute procedure public.handle_new_bs_user();

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Profile owner or admin can read" on public.profiles;
create policy "Profile owner or admin can read"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_bs_admin());

drop policy if exists "Profile owner can update basic details" on public.profiles;
create policy "Profile owner can update basic details"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()) and role = 'customer');

drop policy if exists "Active products are public" on public.products;
create policy "Active products are public"
on public.products for select
using (is_active = true or public.is_bs_admin());

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products"
on public.products for all to authenticated
using (public.is_bs_admin())
with check (public.is_bs_admin());

drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders"
on public.orders for select to authenticated
using (customer_id = (select auth.uid()) or public.is_bs_admin());

drop policy if exists "Customers create own pending orders" on public.orders;
create policy "Customers create own pending orders"
on public.orders for insert to authenticated
with check (
  customer_id = (select auth.uid())
  and status = 'pending'
);

drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders"
on public.orders for update to authenticated
using (public.is_bs_admin())
with check (public.is_bs_admin());

drop policy if exists "Customers read own order items" on public.order_items;
create policy "Customers read own order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1 from public.orders o
    where o.id = order_id
      and (o.customer_id = (select auth.uid()) or public.is_bs_admin())
  )
);

